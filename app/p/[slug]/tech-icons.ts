// Separators that are purely cosmetic variation ("React JS" vs
// "React.js" vs "react-js" vs "ReactJS") get collapsed before a second
// lookup pass -- but only after an exact match fails, so meaningful
// characters like "#" in "C#" or "+" in "C++" (already their own exact
// keys above) are never touched and can't collide with each other.
const SEPARATOR_RE = /[\s.\-_/]+/g;

const ICON_BY_STRIPPED_KEY: Record<string, SimpleIcon> = {};
for (const [key, icon] of Object.entries(ICON_BY_NORMALIZED_NAME)) {
  const stripped = key.replace(SEPARATOR_RE, '');
  if (!(stripped in ICON_BY_STRIPPED_KEY)) {
    ICON_BY_STRIPPED_KEY[stripped] = icon;
  }
}

export function getTechIcon(skillTitle: string): SimpleIcon | null {
  const key = skillTitle.trim().toLowerCase();
  if (ICON_BY_NORMALIZED_NAME[key]) return ICON_BY_NORMALIZED_NAME[key];
  return ICON_BY_STRIPPED_KEY[key.replace(SEPARATOR_RE, '')] ?? null;
}
